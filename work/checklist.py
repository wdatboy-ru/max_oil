def scores():
    W = sum(i[4] for i in ITEMS)
    comp = sum(i[2] * i[4] for i in ITEMS) / W
    rel = sum(i[3] * i[4] * (1 if i[2] > 0 else 0) for i in ITEMS) / W
    groups = {}
    for g, p, c, r, w, _ in ITEMS:
        a = groups.setdefault(g, [0, 0, 0])
        a[0] += c * w; a[1] += r * w; a[2] += w
    return comp, rel, {g: (a[0] / a[2], a[1] / a[2]) for g, a in groups.items()}

